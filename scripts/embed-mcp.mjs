// Embeds mcp/memory-mcp.mjs into server/mcp-source.ts. Paseo bundles the server
// entry, so the plugin cannot rely on the script staying next to it on disk;
// it writes the embedded copy into the memory directory at startup instead.
// Run `npm run embed` after editing the MCP server.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const source = fs.readFileSync(path.join(root, "mcp", "memory-mcp.mjs"), "utf8").replace(/\r\n/g, "\n");

fs.writeFileSync(
  path.join(root, "server", "mcp-source.ts"),
  "// Generated by scripts/embed-mcp.mjs from mcp/memory-mcp.mjs. Do not edit.\n" +
    "export const MCP_SERVER_SOURCE = " +
    JSON.stringify(source) +
    ";\n",
);
